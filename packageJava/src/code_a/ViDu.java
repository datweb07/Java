package code_a;

public class ViDu {
    private int a;
    private int b;

    public ViDu(int a, int b){
        this.a = a;
        this.b = b;
    }

    public int getA(){
        return this.a;
    }

    public int setA(int a){
        return this.a = a;
    }

    public int getB() {
        return this.b;
    }

    public int setB(int b) {
        return this.b = b;
    }
}
