package code_b;

public class ViDu {
    private int a, b, c;

    public ViDu(int a, int c, int b) {
        this.a = a;
        this.c = c;
        this.b = b;
    }

    public int getA() {
        return a;
    }

    public void setA(int a) {
        this.a = a;
    }

    public int getB() {
        return b;
    }

    public void setB(int b) {
        this.b = b;
    }

    public int getC() {
        return c;
    }

    public void setC(int c) {
        this.c = c;
    }
}
